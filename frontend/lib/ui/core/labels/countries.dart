/// stand-in (DESIGN.md §4): Chinese Taipei is the one such entry, because
/// its football flag is not the flag of its ISO code.
///
/// This file is one lookup table and its two accessors. It is longer than
/// the usual module budget because the table is data; splitting it
/// alphabetically would scatter one vocabulary across files.
